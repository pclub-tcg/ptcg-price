_KEYS = sorted(OPZH, key=len, reverse=True)


def op2zh(name):
    """整個名字或名字開頭能對上就翻；「＆」連名的兩邊分別翻。"""
    n = unicodedata.normalize("NFKC", name or "").strip()
    if not n:
        return ""
    if n in OPZH:
        return OPZH[n]
    parts = re.split(r"[&＆]", n)
    if len(parts) > 1:
        zs = [op2zh(p) for p in parts]
        return "&".join(z or p for z, p in zip(zs, parts)) if any(zs) else ""
    for k in _KEYS:
        if n.startswith(k):
            rest = n[len(k):].strip(" ・")
            return OPZH[k] + (" " + rest if rest else "")
    return ""
